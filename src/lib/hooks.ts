/**
 * Walk up from `startDir` looking for a directory containing `.git/`.
 * Returns the project root path, or null if not found.
 */
export function findProjectRoot(startDir: string): string | null {
	let dir = startDir;
	const { root } = parse(dir);
	while (dir !== root) {
		if (existsSync(join(dir, ".git"))) {
			return dir;
		}
		dir = dirname(dir);
	}
	// Check the filesystem root too
	if (existsSync(join(root, ".git"))) {
		return root;
	}
	return null;
}

/**
 * Get the path to the hook script inside .interlinked/hooks/.
 */
export function getHookScriptPath(cwd: string): string {
	return join(cwd, ".interlinked", "hooks", "interlinked-activity.mjs");
}

