// Marker used to identify Interlinked CLI-managed hook entries
const INTERLINKED_MARKER = "interlinked-activity";

// Hook script version — derived from package.json so there's one source of truth.
// Embedded in the generated .mjs script for staleness detection by `doctor`.
export const HOOK_SCRIPT_VERSION: string = ((): string => {
	try {
		const pkgPath = new URL("../../package.json", import.meta.url);
		const pkg = JSON.parse(readFileSync(pkgPath, "utf-8"));
		return pkg.version || "0.0.0";
	} catch (_err) {
		/* intentional: package.json missing or unreadable — fallback version */
		return "0.0.0";
	}
})();

// Claude Code hook events registered in settings.json.
// PostToolUseFailure is intentionally omitted — registering it causes Claude Code
// to display "2 PostToolUse hooks ran" since it counts both registrations.
// The hook script still handles PostToolUseFailure if received (via isPostTool check).
const CLAUDE_HOOK_EVENTS = [
	"SessionStart",
	"SessionEnd",
	"UserPromptSubmit",
	"Stop",
	"PreToolUse",
	"PostToolUse",
	"PermissionRequest",
	"SubagentStart",
	"SubagentStop",
	"Notification",
	"PreCompact",
	"TaskCompleted",
	"TeammateIdle",
] as const;

// PostToolUse matcher — scope to mutating tools only.
// With matcher: "" (match-all), Claude Code counts a PostToolUse hook invocation
// for every tool in the turn (e.g. Read + Edit = "2 hooks ran"). Scoping to
// Edit|Write|MultiEdit ensures the count reflects actual mutations only.
// The hook script still receives all PostToolUse events that match this pattern.
const POST_TOOL_USE_MATCHER = "Edit|Write|MultiEdit";

// GitHub Copilot CLI hook events (camelCase — Copilot convention)
const COPILOT_HOOK_EVENTS = [
	"sessionStart",
	"sessionEnd",
	"userPromptSubmitted",
	"preToolUse",
	"postToolUse",
	"errorOccurred",
] as const;

interface HookEntry {
	matcher: string;
	hooks: Array<{ type: string; command: string }>;
}

