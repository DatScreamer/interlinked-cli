const GITIGNORE_ENTRIES = [
	".interlinked/config.local.json",
	".interlinked/activity.jsonl",
	".interlinked/realtime-retry.jsonl",
	".interlinked/sync-errors.jsonl",
	".interlinked/sync-state.json",
	".interlinked/sessions/",
	".interlinked/checkpoints.json",
	".interlinked/guard-cache.json",
	".interlinked/guard-rules.local.json",
	".interlinked/harness.sock",
	".interlinked/harness.pid",
	".interlinked/pending-quality-warnings.json",
	".interlinked/index/",
	".interlinked/error-history.jsonl",
];

/**
 * Ensure .gitignore contains entries for Interlinked CLI local files.
 * Skips data-related entries when data dir is outside the repo.
 * Returns true if modifications were made.
 */
export function ensureGitignore(cwd: string): boolean {
	const gitignorePath = join(cwd, ".gitignore");
	let content = "";

	if (existsSync(gitignorePath)) {
		content = readFileSync(gitignorePath, "utf-8");
	}

	// Check if data dir is external (skip data gitignore entries)
	const dataRelated = new Set([
		".interlinked/activity.jsonl",
		".interlinked/realtime-retry.jsonl",
		".interlinked/sync-errors.jsonl",
		".interlinked/sync-state.json",
		".interlinked/sessions/",
		".interlinked/checkpoints.json",
	]);
	const envDataDir = process.env.INTERLINKED_DATA_DIR?.trim();
	const isExternalData = envDataDir && !envDataDir.startsWith(cwd);

	const lines = content.split("\n");
	const missingEntries: string[] = [];

	for (const entry of GITIGNORE_ENTRIES) {
		if (isExternalData && dataRelated.has(entry)) continue;
		const alreadyPresent = lines.some(
			(line) => line.trim() === entry || line.trim() === entry.replace(/\/$/, ""),
		);
		if (!alreadyPresent) {
			missingEntries.push(entry);
		}
	}

	if (missingEntries.length === 0) return false;

	// Add a section header if we're adding entries
	const additions: string[] = [];
	if (!content.includes("# Interlinked CLI") && !content.includes("# Interlinked")) {
		additions.push("");
		additions.push("# Interlinked CLI (local agent config)");
	}
	additions.push(...missingEntries);

	const newContent = `${content.trimEnd()}\n${additions.join("\n")}\n`;
	writeFileSync(gitignorePath, newContent);
	return true;
}

// ===========================================
// Hook Manager Detection
// ===========================================

interface HookManagerInfo {
	name: string;
	detected_at: string;
}

/**
 * Detect common git hook managers in the project.
 */
export function detectHookManagers(cwd: string): HookManagerInfo[] {
	const managers: HookManagerInfo[] = [];

	// Husky
	const huskyDir = join(cwd, ".husky");
	if (existsSync(huskyDir)) {
		managers.push({ name: "husky", detected_at: ".husky/" });
	} else {
		// Check package.json for husky references
		const pkgPath = join(cwd, "package.json");
		if (existsSync(pkgPath)) {
			try {
				const pkg = JSON.parse(readFileSync(pkgPath, "utf-8"));
				if (
					pkg.devDependencies?.husky ||
					pkg.dependencies?.husky ||
					pkg.scripts?.prepare?.includes("husky")
				) {
					managers.push({ name: "husky", detected_at: "package.json" });
				}
			} catch (_err) {
				/* intentional: malformed package.json — skip husky detection */
			}
		}
	}

	// Lefthook
	const lefthookFiles = ["lefthook.yml", ".lefthook.yml", "lefthook.yaml", ".lefthook.yaml"];
	for (const file of lefthookFiles) {
		if (existsSync(join(cwd, file))) {
			managers.push({ name: "lefthook", detected_at: file });
			break;
		}
	}
	if (!managers.some((m) => m.name === "lefthook")) {
		const pkgPath = join(cwd, "package.json");
		if (existsSync(pkgPath)) {
			try {
				const pkg = JSON.parse(readFileSync(pkgPath, "utf-8"));
				if (pkg.devDependencies?.lefthook || pkg.dependencies?.lefthook) {
					managers.push({ name: "lefthook", detected_at: "package.json" });
				}
			} catch (_err) {
				/* intentional: malformed package.json — skip lefthook detection */
			}
		}
	}

	// Overcommit
	if (existsSync(join(cwd, ".overcommit.yml"))) {
		managers.push({ name: "overcommit", detected_at: ".overcommit.yml" });
	}

	return managers;
}

// ===========================================
// JSON File Helpers
// ===========================================

function readJsonFile(path: string): JsonObject | null {
	if (!existsSync(path)) return null;
	try {
		return JSON.parse(readFileSync(path, "utf-8"));
	} catch (_err) {
		/* intentional: malformed JSON — caller treats null as "no config" */
		return null;
	}
}

function writeJsonFile(path: string, data: JsonObject): void {
	const dir = dirname(path);
	if (!existsSync(dir)) {
		mkdirSync(dir, { recursive: true });
	}
	writeFileSync(path, `${JSON.stringify(data, null, 2)}\n`);
}

function buildHookCommand(hookScriptPath: string): string {
	const escapedPath = hookScriptPath.replace(/(["\\`$])/g, "\\$1");
	// Guard: exit silently if the script doesn't exist (e.g., agent running from a subdirectory)
	return `test -f "${escapedPath}" && node "${escapedPath}" || true`;
}
