/**
 * Write the universal hook script to .interlinked/hooks/interlinked-activity.mjs.
 * This script reads config from .interlinked/config.local.json and
 * normalizes events from any supported AI coding client.
 */
export function writeHookScript(cwd: string): string {
	const scriptPath = getHookScriptPath(cwd);
	const hookDir = dirname(scriptPath);
	if (!existsSync(hookDir)) {
		mkdirSync(hookDir, { recursive: true });
	}

	// Always write the fresh hook script with local JSONL support.
	// Legacy scripts from .claude/hooks/ are NOT copied — they lack local writing.
	const script = buildHookScript(HOOK_SCRIPT_VERSION);

	writeFileSync(scriptPath, script);
	chmodSync(scriptPath, 0o755);
	return scriptPath;
}

/**
 * Delete the hook script from .interlinked/hooks/.
 */
export function deleteHookScript(cwd: string): boolean {
	const scriptPath = getHookScriptPath(cwd);
	if (existsSync(scriptPath)) {
		unlinkSync(scriptPath);
		return true;
	}
	return false;
}

/**
 * Delete the entire .interlinked/ directory.
 */
export function deleteConfigDir(cwd: string): boolean {
	const configDir = join(cwd, ".interlinked");
	if (existsSync(configDir)) {
		rmSync(configDir, { recursive: true, force: true });
		return true;
	}
	return false;
}

// ===========================================
// Hook Installation — All Clients
// ===========================================

interface InstallResult {
	client: ClientName;
	installed: boolean;
	events: string[];
	error?: string;
}

/**
 * Per-client install/uninstall configuration.
 * To add a new client: add an entry here and implement the install/uninstall functions.
 */
interface ClientInstallEntry {
	events: readonly string[];
	install: (cwd: string, hookScriptPath: string) => void;
	uninstall: (cwd: string) => boolean;
}

const CLIENT_INSTALL_REGISTRY: Record<ClientName, ClientInstallEntry> = {
	claude: {
		events: CLAUDE_HOOK_EVENTS,
		install: installAllClaudeHooks,
		uninstall: uninstallAllClaudeHooks,
	},
	copilot: {
		events: COPILOT_HOOK_EVENTS,
		install: installCopilotHooks,
		uninstall: uninstallCopilotHooks,
	},
	gemini: {
		events: GEMINI_HOOK_EVENTS,
		install: installGeminiHooks,
		uninstall: uninstallGeminiHooks,
	},
	// Future clients:
	// cursor: { events: CURSOR_HOOK_EVENTS, install: installCursorHooks, uninstall: uninstallCursorHooks },
};

/**
 * Install hooks into all specified clients.
 * Uses CLIENT_INSTALL_REGISTRY — add new clients there, not here.
 */
export function installAllHooks(
	cwd: string,
	hookScriptPath: string,
	clients: ClientName[],
): InstallResult[] {
	return clients.map((client) => {
		const entry = CLIENT_INSTALL_REGISTRY[client];
		if (!entry) {
			return { client, installed: false, events: [], error: `Unknown client: ${client}` };
		}
		try {
			entry.install(cwd, hookScriptPath);
			return { client, installed: true, events: [...entry.events] };
		} catch (e) {
			return {
				client,
				installed: false,
				events: [],
				error: e instanceof Error ? e.message : String(e),
			};
		}
	});
}

/**
 * Uninstall hooks from all specified clients.
 * Uses CLIENT_INSTALL_REGISTRY — add new clients there, not here.
 */
export function uninstallAllHooks(cwd: string, clients: ClientName[]): InstallResult[] {
	return clients.map((client) => {
		const entry = CLIENT_INSTALL_REGISTRY[client];
		if (!entry) {
			return { client, installed: false, events: [], error: `Unknown client: ${client}` };
		}
		try {
			const removed = entry.uninstall(cwd);
			return { client, installed: false, events: removed ? [...entry.events] : [] };
		} catch (e) {
			return {
				client,
				installed: false,
				events: [],
				error: e instanceof Error ? e.message : String(e),
			};
		}
	});
}

// ===========================================
// Claude Code — Full 14-Event Installation
// ===========================================

function getClaudeSettingsPath(cwd: string): string {
	return join(cwd, ".claude", "settings.json");
}

function installAllClaudeHooks(cwd: string, hookScriptPath: string): void {
	// Refuse to install if a parent directory already has interlinked hooks.
	// Claude Code merges hooks from all .claude/settings.json files in the path,
	// so duplicate registrations cause "2 PostToolUse hooks ran" and can swallow output.
	const parentWithHooks = findParentWithHooks(cwd, join(".claude", "settings.json"));
	if (parentWithHooks) {
		console.error(
			`\n⚠️  Skipping Claude hook installation — hooks already installed at ${parentWithHooks}/.claude/settings.json\n` +
				"   Claude Code merges hooks from all .claude/settings.json files in the path,\n" +
				"   so installing here would cause duplicate hooks.\n" +
				`   Run \`interlinked enable\` from ${parentWithHooks} instead.\n`,
		);
		return;
	}

	const settingsPath = getClaudeSettingsPath(cwd);
	const settings = readJsonFile(settingsPath) || {};

	if (!settings.hooks) settings.hooks = {};
	const hooks = settings.hooks as JsonObject;

	const hookCommand = buildHookCommand(hookScriptPath);

	for (const eventName of CLAUDE_HOOK_EVENTS) {
		installHookEntry(hooks, eventName, hookCommand);
	}

	writeJsonFile(settingsPath, settings);
}

/**
 * Walk up from cwd to the git root checking if any ancestor already has
 * interlinked hooks in the given settings file. Returns the ancestor path
 * if found, or null if no parent has hooks.
 */
function findParentWithHooks(cwd: string, settingsSubpath: string): string | null {
	const gitRoot = findProjectRoot(cwd);
	let dir = dirname(cwd);
	const stopAt = gitRoot || parse(cwd).root;

	while (dir.length >= stopAt.length) {
		const settingsPath = join(dir, settingsSubpath);
		if (existsSync(settingsPath)) {
			try {
				const content = readFileSync(settingsPath, "utf-8");
				if (content.includes(INTERLINKED_MARKER)) {
					return dir;
				}
			} catch (_err) {
				/* intentional: settings file unreadable — keep walking up */
			}
		}
		const parent = dirname(dir);
		if (parent === dir) break;
		dir = parent;
	}
	return null;
}

function cleanClaudeHooksFromFile(settingsPath: string): boolean {
	if (!existsSync(settingsPath)) return false;

	const settings = readJsonFile(settingsPath);
	if (!settings?.hooks) return false;

	const hooks = settings.hooks as JsonObject;
	let changed = false;
	for (const eventName of CLAUDE_HOOK_EVENTS) {
		const entries = hooks[eventName] as HookEntry[] | undefined;
		if (!entries) continue;

		const filtered = entries.filter(
			(entry: HookEntry) =>
				!entry.hooks?.some((h) => h.command?.includes(INTERLINKED_MARKER)),
		);

		if (filtered.length !== entries.length) {
			hooks[eventName] = filtered.length > 0 ? filtered : undefined;
			changed = true;
		}
	}

	// Clean up empty hooks object
	if (Object.values(hooks).every((v) => v === undefined)) {
		delete settings.hooks;
	}

	if (changed) {
		writeJsonFile(settingsPath, settings);
	}
	return changed;
}

function uninstallAllClaudeHooks(cwd: string): boolean {
	let changed = false;

	// Clean hooks from cwd's .claude/settings.json
	changed = cleanClaudeHooksFromFile(getClaudeSettingsPath(cwd)) || changed;

	// Also clean hooks from the git root's .claude/settings.json
	const projectRoot = findProjectRoot(cwd);
	if (projectRoot && projectRoot !== cwd) {
		changed = cleanClaudeHooksFromFile(getClaudeSettingsPath(projectRoot)) || changed;
	}

	return changed;
}

// ===========================================
// GitHub Copilot CLI — Install/Uninstall
// ===========================================

function getCopilotHooksPath(cwd: string): string {
	return join(cwd, ".github", "hooks", "hooks.json");
}

function installCopilotHooks(cwd: string, hookScriptPath: string): void {
	const hooksPath = getCopilotHooksPath(cwd);
	const dir = dirname(hooksPath);
	if (!existsSync(dir)) {
		mkdirSync(dir, { recursive: true });
	}

	const hookCommand = buildHookCommand(hookScriptPath);

	// Read existing config or start fresh
	let config: { version: number; hooks: Record<string, unknown[]> };
	if (existsSync(hooksPath)) {
		try {
			config = JSON.parse(readFileSync(hooksPath, "utf-8"));
			if (!config.hooks || typeof config.hooks !== "object") {
				config.hooks = {};
			}
		} catch (_err) {
			/* intentional: malformed hooks.json — start over with empty config */
			config = { version: 1, hooks: {} };
		}
	} else {
		config = { version: 1, hooks: {} };
	}

	for (const eventName of COPILOT_HOOK_EVENTS) {
		if (!config.hooks[eventName]) config.hooks[eventName] = [];
		const entries = config.hooks[eventName] as Array<{ type: string; bash?: string }>;

		// Check if already installed — update if stale
		const existing = entries.find((e) => e.bash?.includes(INTERLINKED_MARKER));
		if (existing) {
			if (existing.bash !== hookCommand) {
				existing.bash = hookCommand;
			}
			continue;
		}

		entries.push({
			type: "command",
			bash: hookCommand,
		});
	}

	config.version = 1;
	writeFileSync(hooksPath, `${JSON.stringify(config, null, 2)}\n`);
}

function uninstallCopilotHooks(cwd: string): boolean {
	const hooksPath = getCopilotHooksPath(cwd);
	if (!existsSync(hooksPath)) return false;

	let config: { version?: number; hooks?: Record<string, unknown[]> };
	try {
		config = JSON.parse(readFileSync(hooksPath, "utf-8"));
	} catch (_err) {
		/* intentional: unreadable copilot hooks.json — nothing to uninstall */
		return false;
	}
	if (!config.hooks) return false;

	let changed = false;
	for (const eventName of COPILOT_HOOK_EVENTS) {
		const entries = config.hooks[eventName] as
			| Array<{ type: string; bash?: string }>
			| undefined;
		if (!entries) continue;

		const filtered = entries.filter((e) => !e.bash?.includes(INTERLINKED_MARKER));
		if (filtered.length !== entries.length) {
			config.hooks[eventName] = filtered.length > 0 ? filtered : [];
			changed = true;
		}
	}

	if (changed) {
		// Remove file entirely if no hooks remain
		const hasHooks = Object.values(config.hooks).some(
			(arr) => Array.isArray(arr) && arr.length > 0,
		);
		if (!hasHooks) {
			rmSync(hooksPath, { force: true });
		} else {
			writeFileSync(hooksPath, `${JSON.stringify(config, null, 2)}\n`);
		}
	}

	return changed;
}

// ===========================================
// Shared Hook Entry Helper
// ===========================================

function installHookEntry(hooks: JsonObject, eventName: string, command: string): void {
	if (!hooks[eventName]) hooks[eventName] = [];
	const entries = hooks[eventName] as HookEntry[];

	// Check if already installed
	const existing = entries.find((entry) =>
		entry.hooks?.some((h) => h.command?.includes(INTERLINKED_MARKER)),
	);

	if (existing) {
		// Update command if it points to a stale path (e.g. .claude/hooks/ → .interlinked/hooks/)
		const hook = existing.hooks?.find((h) => h.command?.includes(INTERLINKED_MARKER));
		if (hook && hook.command !== command) {
			hook.command = command;
		}
		// Update matcher for PostToolUse (was "" catch-all, now scoped to mutating tools)
		const expectedMatcher = eventName === "PostToolUse" ? POST_TOOL_USE_MATCHER : "";
		if (existing.matcher !== expectedMatcher) {
			existing.matcher = expectedMatcher;
		}
		return;
	}

	entries.push({
		matcher: eventName === "PostToolUse" ? POST_TOOL_USE_MATCHER : "",
		hooks: [{ type: "command", command }],
	});
}

